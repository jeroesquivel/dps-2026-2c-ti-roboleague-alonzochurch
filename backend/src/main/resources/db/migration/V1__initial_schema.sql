-- Esquema inicial. Cada agregado del dominio se guarda como un documento JSON en `payload`; el resto de las
-- columnas son las claves por las que se lo busca. Es SQL estándar: corre igual en PostgreSQL y en H2.

CREATE TABLE seasons (
    id          VARCHAR(200) PRIMARY KEY,
    sort_order  BIGINT       NOT NULL,
    payload     TEXT         NOT NULL
);

CREATE TABLE competitions (
    id          VARCHAR(200) PRIMARY KEY,
    season_id   VARCHAR(100) NOT NULL,
    payload     TEXT         NOT NULL
);

CREATE TABLE rulebooks (
    id              VARCHAR(200) PRIMARY KEY,
    competition_id  VARCHAR(100) NOT NULL,
    version         INTEGER      NOT NULL,
    payload         TEXT         NOT NULL,
    CONSTRAINT uq_rulebook_version UNIQUE (competition_id, version)
);

CREATE TABLE team_registrations (
    id              VARCHAR(200) PRIMARY KEY,
    competition_id  VARCHAR(100) NOT NULL,
    category_id     VARCHAR(100) NOT NULL,
    payload         TEXT         NOT NULL
);

CREATE TABLE rounds (
    id              VARCHAR(200) PRIMARY KEY,
    competition_id  VARCHAR(100) NOT NULL,
    category_id     VARCHAR(100) NOT NULL,
    ordinal         INTEGER      NOT NULL,
    payload         TEXT         NOT NULL
);
CREATE INDEX ix_rounds_competition ON rounds (competition_id, category_id, ordinal);

CREATE TABLE run_results (
    id              VARCHAR(200) PRIMARY KEY,
    round_id        VARCHAR(100) NOT NULL,
    team_id         VARCHAR(100) NOT NULL,
    attempt_number  INTEGER      NOT NULL,
    payload         TEXT         NOT NULL,
    CONSTRAINT uq_run_attempt UNIQUE (round_id, team_id, attempt_number)
);

CREATE TABLE standings (
    id              VARCHAR(200) PRIMARY KEY,
    competition_id  VARCHAR(100) NOT NULL,
    category_id     VARCHAR(100) NOT NULL,
    revision        INTEGER      NOT NULL,
    payload         TEXT         NOT NULL,
    CONSTRAINT uq_standings_revision UNIQUE (competition_id, category_id, revision)
);

CREATE TABLE appeals (
    id          VARCHAR(200) PRIMARY KEY,
    run_id      VARCHAR(100) NOT NULL,
    payload     TEXT         NOT NULL
);
CREATE INDEX ix_appeals_run ON appeals (run_id);

CREATE TABLE audit_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type  VARCHAR(200) NOT NULL,
    subject_id    VARCHAR(100) NOT NULL,
    payload       TEXT         NOT NULL
);
CREATE INDEX ix_audit_subject ON audit_events (subject_type, subject_id);

